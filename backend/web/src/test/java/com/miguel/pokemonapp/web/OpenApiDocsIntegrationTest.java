package com.miguel.pokemonapp.web;

import com.miguel.pokemonapp.support.PostgresTestcontainersConfiguration;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.resttestclient.autoconfigure.AutoConfigureRestTestClient;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.test.context.SpringBootTest.WebEnvironment;
import org.springframework.context.annotation.Import;
import org.springframework.http.MediaType;
import org.springframework.test.web.servlet.client.RestTestClient;

@SpringBootTest(webEnvironment = WebEnvironment.RANDOM_PORT)
@AutoConfigureRestTestClient
@Import(PostgresTestcontainersConfiguration.class)
class OpenApiDocsIntegrationTest {

  @Test
  void apiDocsReturnsOpenApiJson(@Autowired RestTestClient restClient) {
    restClient
        .get()
        .uri("/v3/api-docs")
        .exchange()
        .expectStatus()
        .isOk()
        .expectHeader()
        .contentTypeCompatibleWith(MediaType.APPLICATION_JSON)
        .expectBody()
        .jsonPath("$.openapi")
        .exists()
        .jsonPath("$.info.title")
        .isEqualTo("Pokéfolio API")
        .jsonPath("$.paths['/api/v1/pokemon'].get.parameters[?(@.name=='page')].in")
        .isEqualTo("query")
        .jsonPath("$.paths['/api/v1/pokemon'].get.parameters[?(@.name=='page')].required")
        .isEqualTo(false)
        .jsonPath("$.paths['/api/v1/pokemon'].get.parameters[?(@.name=='size')].in")
        .isEqualTo("query")
        .jsonPath("$.paths['/api/v1/pokemon'].get.parameters[?(@.name=='size')].required")
        .isEqualTo(false)
        .jsonPath("$.paths['/api/v1/pokemon'].get.responses['200']")
        .exists()
        .jsonPath("$.paths['/api/v1/pokemon'].get.responses['200'].content['application/json']")
        .exists()
        .jsonPath("$.paths['/api/v1/pokemon'].get.responses['400']")
        .exists()
        .jsonPath("$.paths['/api/v1/pokemon'].get.responses['502']")
        .exists()
        .jsonPath("$.paths['/api/v1/pokemon/{id}'].get.parameters[?(@.name=='id')].in")
        .isEqualTo("path")
        .jsonPath("$.paths['/api/v1/pokemon/{id}'].get.responses['200']")
        .exists()
        .jsonPath(
            "$.paths['/api/v1/pokemon/{id}'].get.responses['200'].content['application/json']")
        .exists()
        .jsonPath("$.paths['/api/v1/pokemon/{id}'].get.responses['400']")
        .exists()
        .jsonPath("$.paths['/api/v1/pokemon/{id}'].get.responses['404']")
        .exists()
        .jsonPath("$.paths['/api/v1/pokemon/{id}'].get.responses['502']")
        .exists()
        .jsonPath("$.paths['/api/v1/collection'].post.responses['201']")
        .exists()
        .jsonPath("$.paths['/api/v1/collection'].post.responses['201'].content['application/json']")
        .exists()
        .jsonPath(
            "$.paths['/api/v1/collection'].post.responses['400'].content['application/problem+json']")
        .exists()
        .jsonPath(
            "$.paths['/api/v1/collection'].post.responses['404'].content['application/problem+json']")
        .exists()
        .jsonPath(
            "$.paths['/api/v1/collection'].post.responses['409'].content['application/problem+json']")
        .exists()
        .jsonPath(
            "$.paths['/api/v1/collection'].post.responses['502'].content['application/problem+json']")
        .exists()
        .jsonPath("$.paths['/api/v1/collection'].get.responses['200']")
        .exists()
        .jsonPath("$.paths['/api/v1/collection'].get.responses['200'].content['application/json']")
        .exists()
        .jsonPath(
            "$.paths['/api/v1/collection'].get.responses['400'].content['application/problem+json']")
        .exists()
        .jsonPath("$.paths['/api/v1/collection/{nationalNumber}'].get.responses['200']")
        .exists()
        .jsonPath(
            "$.paths['/api/v1/collection/{nationalNumber}'].get.responses['200'].content['application/json']")
        .exists()
        .jsonPath(
            "$.paths['/api/v1/collection/{nationalNumber}'].get.responses['400'].content['application/problem+json']")
        .exists()
        .jsonPath(
            "$.paths['/api/v1/collection/{nationalNumber}'].get.responses['404'].content['application/problem+json']")
        .exists()
        .jsonPath("$.paths['/api/v1/collection/{nationalNumber}'].put.responses['200']")
        .exists()
        .jsonPath(
            "$.paths['/api/v1/collection/{nationalNumber}'].put.responses['200'].content['application/json']")
        .exists()
        .jsonPath(
            "$.paths['/api/v1/collection/{nationalNumber}'].put.responses['400'].content['application/problem+json']")
        .exists()
        .jsonPath(
            "$.paths['/api/v1/collection/{nationalNumber}'].put.responses['404'].content['application/problem+json']")
        .exists()
        .jsonPath(
            "$.paths['/api/v1/collection/{nationalNumber}'].put.responses['409'].content['application/problem+json']")
        .exists()
        .jsonPath(
            "$.paths['/api/v1/collection/{nationalNumber}'].put.responses['415'].content['application/problem+json']")
        .exists()
        .jsonPath("$.paths['/api/v1/collection/{nationalNumber}'].delete.responses['204']")
        .exists()
        .jsonPath(
            "$.paths['/api/v1/collection/{nationalNumber}'].delete.responses['404'].content['application/problem+json']")
        .exists()
        .jsonPath("$.components.schemas.LocalPokemonResponse.properties.version")
        .exists()
        .jsonPath("$.components.securitySchemes.bearerAuth.type")
        .isEqualTo("http")
        .jsonPath("$.components.securitySchemes.bearerAuth.scheme")
        .isEqualTo("bearer")
        .jsonPath("$.components.securitySchemes.bearerAuth.bearerFormat")
        .isEqualTo("JWT")
        .jsonPath("$.paths['/api/v1/collection'].post.security[0].bearerAuth")
        .exists()
        .jsonPath(
            "$.paths['/api/v1/collection'].post.responses['401'].content['application/problem+json']")
        .exists()
        .jsonPath(
            "$.paths['/api/v1/collection'].post.responses['403'].content['application/problem+json']")
        .exists()
        .jsonPath("$.paths['/api/v1/collection/{nationalNumber}'].put.security[0].bearerAuth")
        .exists()
        .jsonPath(
            "$.paths['/api/v1/collection/{nationalNumber}'].put.responses['401'].content['application/problem+json']")
        .exists()
        .jsonPath(
            "$.paths['/api/v1/collection/{nationalNumber}'].put.responses['403'].content['application/problem+json']")
        .exists()
        .jsonPath("$.paths['/api/v1/collection/{nationalNumber}'].delete.security[0].bearerAuth")
        .exists()
        .jsonPath(
            "$.paths['/api/v1/collection/{nationalNumber}'].delete.responses['401'].content['application/problem+json']")
        .exists()
        .jsonPath(
            "$.paths['/api/v1/collection/{nationalNumber}'].delete.responses['403'].content['application/problem+json']")
        .exists()
        .jsonPath("$.paths['/api/v1/pokemon'].get.security")
        .doesNotExist()
        .jsonPath("$.paths['/api/v1/pokemon/{id}'].get.security")
        .doesNotExist()
        .jsonPath("$.paths['/api/v1/collection'].get.security")
        .doesNotExist()
        .jsonPath("$.paths['/api/v1/collection/{nationalNumber}'].get.security")
        .doesNotExist()
        .jsonPath("$.paths['/api/v1/auth/register'].post.security")
        .doesNotExist()
        .jsonPath("$.paths['/api/v1/auth/login'].post.security")
        .doesNotExist()
        .jsonPath("$.paths['/api/v1/auth/register'].post.responses['201']")
        .exists()
        .jsonPath(
            "$.paths['/api/v1/auth/register'].post.responses['400'].content['application/problem+json']")
        .exists()
        .jsonPath(
            "$.paths['/api/v1/auth/register'].post.responses['409'].content['application/problem+json']")
        .exists()
        .jsonPath("$.paths['/api/v1/auth/login'].post.responses['200']")
        .exists()
        .jsonPath(
            "$.paths['/api/v1/auth/login'].post.responses['400'].content['application/problem+json']")
        .exists()
        .jsonPath(
            "$.paths['/api/v1/auth/login'].post.responses['401'].content['application/problem+json']")
        .exists();
  }
}
